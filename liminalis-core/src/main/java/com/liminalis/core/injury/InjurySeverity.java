package com.liminalis.core.injury;

/**
 * What a blow left behind.
 */
public enum InjurySeverity {

    /** Nothing lasting. Most hits. */
    NONE,

    /** A wound that heals with time, faster with treatment. */
    INJURY,

    /** A lost arm, broken legs. Does not heal on its own. */
    MORTAL_WOUND
}
