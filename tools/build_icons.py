# Shared palette. Keys are the characters used in the grids.
#   .  transparent      o  outline
#   #  body             +  highlight
#   x  accent
TRANSPARENT = (0, 0, 0, 0)


def palette(outline, body, highlight, accent):
    return {
        ".": TRANSPARENT,
        "o": outline,
        "#": body,
        "+": highlight,
        "x": accent,
    }


