def render(name, grid, colours):
    """
    Turns one ASCII grid into a 16x16 icon, refusing anything that is not exactly that.

    The size check is not paranoia. This used to slice the grid to 16x16 and pad the rest
    with transparency, so a row one character short - which is trivially easy when you are
    hand-drawing sixteen of these - produced an icon with a bite out of one edge and no
    complaint from anywhere. At sixteen pixels that reads as a slightly odd drawing rather
    than as a bug, which is exactly how it would survive all the way to a player's screen.
    """
    size = 16
    rows = grid.strip().split("\n")

    if len(rows) != size:
        raise ValueError("%s: grid is %d rows, must be %d" % (name, len(rows), size))
    for y, row in enumerate(rows):
        if len(row) != size:
            raise ValueError("%s: row %d is %d characters, must be %d\n  %r"
                             % (name, y, len(row), size, row))
        unknown = sorted(set(row) - set(colours))
        if unknown:
            raise ValueError("%s: row %d uses unknown characters %s" % (name, y, unknown))

    image = Image.new("RGBA", (size, size), TRANSPARENT)
    pixels = image.load()
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            pixels[x, y] = colours[char]
    return image


def build_pack_icon(path):
    """
    The pack icon: the pale garden reduced to 128 pixels.

    A vertical grey gradient with a single darker band across it - the horizon
    of a place with nothing on it.
    """
    size = 128
    image = Image.new("RGBA", (size, size), (0, 0, 0, 255))
    pixels = image.load()

    for y in range(size):
        # Pale at the top, sinking to near-black at the bottom.
        t = y / (size - 1)
        value = int(176 - (t ** 1.4) * 150)
        for x in range(size):
            # A faint horizontal band two thirds down, like a treeline with no trees.
            band = 18 if 82 <= y <= 86 else 0
            shade = max(0, value - band)
            pixels[x, y] = (shade, shade + 4, shade + 6, 255)

    image.save(path)


def build_font():
    """
    Writes hud.json from CODEPOINTS.

    Generated rather than hand-maintained because a font file that disagrees with the
    textures beside it produces empty boxes on players' screens and no error anywhere.
    """
    providers = [
        {
            "type": "bitmap",
            "file": f"liminalis:font/injury/{name}.png",
            "ascent": 8,
            "height": 10,
            "chars": [chr(cp)],
        }
        for name, cp in CODEPOINTS
    ]
    FONT.parent.mkdir(parents=True, exist_ok=True)
    # Line endings are pinned to LF rather than left to the platform default. Python
    # translates a newline to CRLF on Windows, git normalises the committed file back to LF,
    # and the pack zip hashes whichever bytes are on disk - so without this the sha1 depends
    # on whether you last ran this script or last cloned the repo, and two people building
    # the same commit get two different hashes for identical content.
    FONT.write_text(json.dumps({"providers": providers}, indent=2, ensure_ascii=True) + chr(10),
                    encoding="utf-8", newline=chr(10))


def check_coverage():
    """Every codepoint needs a texture, and every texture needs a codepoint."""
    named = {name for name, _ in CODEPOINTS}
    drawn = set(ICONS)
    missing_art = named - drawn
    missing_codepoint = drawn - named
    if missing_art:
        raise SystemExit(f"codepoints with no icon defined: {sorted(missing_art)}")
    if missing_codepoint:
        raise SystemExit(f"icons with no codepoint: {sorted(missing_codepoint)}")


def main():
    check_coverage()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (grid, colours) in ICONS.items():
        target = OUT / f"{name}.png"
        render(name, grid, colours).save(target)
        print(f"  {target.relative_to(ROOT)}")

    icon = ROOT / "pack" / "pack.png"
    build_pack_icon(icon)
    print(f"  {icon.relative_to(ROOT)}")

    build_font()
    print(f"  {FONT.relative_to(ROOT)}")
    print(f"{len(ICONS)} icons + pack icon + font written")


if __name__ == "__main__":
    main()
